// Ranked words are not in this file: they live only in the database (supabase/ranked-words.sql) and are
// picked by the match server, so they never appear in Solo, Daily Play, Play Locally or unranked online play.

// Pick n words for a difficulty ("easy" | "medium" | "hard" | "mixed").
// Words already seen on this device are skipped until every word at that level has been played.
window.pickWords = function(n, level){
  const lv = {easy:1, medium:2, hard:3}[level];
  const pool = window.WORDS.filter(w => !lv || w[2] === lv);
  const key = "reveal-seen-" + (level || "mixed");
  let seen = [];
  try { seen = JSON.parse(localStorage.getItem(key) || "[]"); } catch(e) {}
  let fresh = pool.filter(w => !seen.includes(w[0]));
  if (fresh.length < n) { seen = []; fresh = pool.slice(); }
  for (let i = fresh.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [fresh[i], fresh[j]] = [fresh[j], fresh[i]]; }
  const picked = fresh.slice(0, n);
  try { localStorage.setItem(key, JSON.stringify(seen.concat(picked.map(w => w[0])))); } catch(e) {}
  return picked;
};
